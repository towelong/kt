"""迁移本身的测试：升级、降级、以及模型与迁移是否已经对齐。"""

import pytest
from alembic import command
from sqlalchemy import create_engine, inspect

from app.migrations import alembic_config, head_revision


@pytest.fixture
def db_url(tmp_path):
    return f"sqlite:///{tmp_path / 'migrate.db'}"


def test_upgrade_and_downgrade(db_url):
    cfg = alembic_config(db_url)

    command.upgrade(cfg, "head")
    engine = create_engine(db_url)
    tables = set(inspect(engine).get_table_names())
    assert {"item", "user", "alembic_version"} <= tables
    engine.dispose()

    command.downgrade(cfg, "base")
    engine = create_engine(db_url)
    assert set(inspect(engine).get_table_names()) == {"alembic_version"}
    engine.dispose()


def test_downgrade_then_upgrade_again(db_url):
    cfg = alembic_config(db_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")

    engine = create_engine(db_url)
    assert "user" in inspect(engine).get_table_names()
    engine.dispose()


def test_models_match_migrations(db_url):
    """改了模型忘了生成迁移，这里会失败。"""
    cfg = alembic_config(db_url)
    command.upgrade(cfg, "head")
    command.check(cfg)  # 有差异会抛 AutogenerateDiffsDetected


